import { chromium } from '@playwright/test';
const out = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://localhost:4173/');
await page.waitForSelector('text=Hire, onboard', { timeout: 180000 });
await page.goto('http://localhost:4173/login?email=hr@nimbus.test');
await page.click('button[type=submit]');
await page.waitForURL('**/app');
await page.getByRole('link', { name: /Communication/ }).click();
await page.getByRole('button', { name: /Engineering/ }).click();
await page.waitForTimeout(1500);
await page.getByRole('button', { name: 'Conversation details' }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/chat-desktop.png` });
await page.setViewportSize({ width: 390, height: 844 });
await page.waitForTimeout(800);
await page.keyboard.press('Escape');
await page.screenshot({ path: `${out}/chat-mobile.png` });
console.log(errors.length ? errors.join('\n') : 'NO ERRORS');
await browser.close();
